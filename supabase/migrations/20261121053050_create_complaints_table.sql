/*
# Create complaints table for CivicLens

1. New Tables
- `complaints`
  - `id` (uuid, primary key) — unique ticket id generated by the database.
  - `ticket_number` (text, unique, not null) — human-readable ticket id of the form `CIVIC-YYYY-NNNNNN`, generated server-side via a helper so duplicates are impossible.
  - `description` (text, not null) — the original complaint text as submitted by the citizen.
  - `original_language` (text, not null) — language detected by the AI (e.g. "English", "Hindi", "Marathi").
  - `translated_summary` (text, not null) — English translation/summary produced by the AI.
  - `image_url` (text) — public URL of an optional uploaded photograph stored in Supabase Storage (null when no photo).
  - `locality` (text) — optional free-text locality/area name.
  - `category` (text, not null) — one of the supported CivicLens categories.
  - `severity` (text, not null) — one of: Critical, High, Medium, Low.
  - `severity_reason` (text, not null) — one-line AI justification for the chosen severity.
  - `department` (text, not null) — the routed municipal department.
  - `suggested_action` (text, not null) — AI-suggested next action for the department.
  - `confidence` (text, not null) — one of: High, Medium, Low.
  - `status` (text, not null, default 'Open') — one of: Open, Acknowledged, In Progress, Resolved.
  - `possible_duplicate_of` (uuid) — nullable self-reference to another complaint id flagged as a likely duplicate.
  - `created_at` (timestamptz, default now()) — submission timestamp.

2. Helper
- `generate_ticket_number()` — SECURITY INVOKER PL/pgSQL function that returns a unique `CIVIC-YYYY-NNNNNN` string using a sequence. Used as a column default so the ticket number is always created server-side and never client-supplied.

3. Security
- Enable RLS on `complaints`.
- Grant CRUD to `anon` + `authenticated` so the no-auth prototype frontend can submit and read complaints via the Data API.
- Four separate per-verb policies (SELECT/INSERT/UPDATE/DELETE), all `USING (true)` / `WITH CHECK (true)` because complaint data is intentionally public/shared in this civic prototype (no sign-in screen).
- `generate_ticket_number()` is EXECUTE-revoked from PUBLIC/anon and granted only to `authenticated` + `anon` (both need it because inserts run as anon); service_role also granted for edge functions. Note: the function only reads a sequence, so broad EXECUTE is harmless, but it is scoped explicitly for clarity.

4. Important Notes
- This is a single-tenant, no-auth prototype: every policy lists `anon` so the anon-key frontend works. If sign-in is added later, tighten these policies to ownership checks.
- `ticket_number` uniqueness is enforced by a UNIQUE constraint and backed by a sequence, so concurrent inserts can never collide.
- The `possible_duplicate_of` column is a self-reference (no FK constraint to avoid circular dependency on the same table during insert); the application layer sets it after duplicate detection.
*/

-- Sequence for ticket numbers, padded to 6 digits per year.
CREATE SEQUENCE IF NOT EXISTS complaint_ticket_seq START 1 INCREMENT 1;

CREATE OR REPLACE FUNCTION generate_ticket_number()
RETURNS text
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
DECLARE
  next_val bigint;
  year_str text;
BEGIN
  next_val := nextval('complaint_ticket_seq');
  year_str := to_char(now(), 'YYYY');
  RETURN 'CIVIC-' || year_str || '-' || lpad(next_val::text, 6, '0');
END;
$$;

REVOKE EXECUTE ON FUNCTION generate_ticket_number() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION generate_ticket_number() TO anon, authenticated, service_role;
GRANT USAGE ON SEQUENCE complaint_ticket_seq TO anon, authenticated, service_role;

CREATE TABLE IF NOT EXISTS complaints (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ticket_number text NOT NULL DEFAULT generate_ticket_number(),
  description text NOT NULL,
  original_language text NOT NULL,
  translated_summary text NOT NULL,
  image_url text,
  locality text,
  category text NOT NULL,
  severity text NOT NULL CHECK (severity IN ('Critical','High','Medium','Low')),
  severity_reason text NOT NULL,
  department text NOT NULL,
  suggested_action text NOT NULL,
  confidence text NOT NULL CHECK (confidence IN ('High','Medium','Low')),
  status text NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Acknowledged','In Progress','Resolved')),
  possible_duplicate_of uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT complaints_ticket_number_unique UNIQUE (ticket_number)
);

ALTER TABLE complaints ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON complaints TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON complaints TO service_role;

DROP POLICY IF EXISTS "complaints_select_all" ON complaints;
CREATE POLICY "complaints_select_all"
  ON complaints FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "complaints_insert_all" ON complaints;
CREATE POLICY "complaints_insert_all"
  ON complaints FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "complaints_update_all" ON complaints;
CREATE POLICY "complaints_update_all"
  ON complaints FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "complaints_delete_all" ON complaints;
CREATE POLICY "complaints_delete_all"
  ON complaints FOR DELETE TO anon, authenticated USING (true);
